    await expect(outlineTarget).toHaveAttribute('data-target-summary', mapFacts.target!)
    await expect(outlineTarget).toHaveAttribute('data-target-status-summary', mapFacts.status!)
    await expect(outlineTarget).toHaveAttribute('data-target-rows', mapFacts.targetRows!)
