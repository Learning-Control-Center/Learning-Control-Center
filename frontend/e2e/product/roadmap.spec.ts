test('Roadmap drag editing persists and remains reversible', async ({ page }) => {
  test.skip(isCompact(page) || expectedSize !== 25, 'Representative desktop drag gate runs on the normal fixture.')
  await login(page)
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  await page.getByRole('button', { name: 'Edit layout' }).click()
  await axe(page)
  const node = page.locator('.roadmap-node').first()
  const nodeId = await node.getAttribute('data-roadmap-node-id')
  const box = await node.boundingBox()
  expect(box).not.toBeNull()
  const canonicalTransform = await node.evaluate((element) => element.parentElement?.style.transform)
  const positionPattern = '**/api/v2/roadmap-projection/*/positions/*'
  await page.route(positionPattern, (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'POSITION_SAVE_FAILED', message: 'Position save failed safely.' } }) }))
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2 + 32, box!.y + box!.height / 2 + 16, { steps: 6 })
  await page.mouse.up()
  await expect(page.getByText('Position save failed safely.')).toBeVisible()
  await expect(node).not.toHaveAttribute('data-position-source', 'user_override')
  await expect.poll(() => node.evaluate((element) => element.parentElement?.style.transform)).toBe(canonicalTransform)
  await page.unroute(positionPattern)
  await page.reload()
  await expect(page.locator('[data-roadmap-ready="true"]')).toBeVisible()
  await page.getByRole('button', { name: 'Edit layout' }).click()
  const retryNode = page.locator(`[data-roadmap-node-id="${nodeId}"]`)
  const retryBox = await retryNode.boundingBox()
  await page.mouse.move(retryBox!.x + retryBox!.width / 2, retryBox!.y + retryBox!.height / 2)
  await page.mouse.down()
  await page.mouse.move(retryBox!.x + retryBox!.width / 2 + 64, retryBox!.y + retryBox!.height / 2 + 24, { steps: 8 })
  await page.mouse.up()
  await expect(page.getByText(/position saved/)).toBeAttached()
  await page.reload()
  await expect(page.locator('[data-roadmap-ready="true"]')).toBeVisible()
  await expect(page.locator(`[data-roadmap-node-id="${nodeId}"]`)).toHaveAttribute('data-position-source', 'user_override')
  await page.getByRole('button', { name: 'Reset layout' }).click()
  await page.getByRole('dialog', { name: 'Reset Roadmap layout' }).getByRole('button', { name: 'Reset layout' }).click()
  await expect(page.getByText(/Canonical layout restored/)).toBeAttached()
})

test('Roadmap reflows across touch, text-spacing, forced-colors, and small-height states', async ({ page }) => {
  test.skip(expectedSize !== 25, 'The complete responsive state matrix runs on the representative 25-node fixture.')
  await login(page)
  const search = page.getByLabel('Search the journey')
  const spacingStyle = await page.addStyleTag({ content: '* { line-height: 1.5 !important; letter-spacing: 0.12em !important; word-spacing: 0.16em !important; } p { margin-bottom: 2em !important; }' })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await search.scrollIntoViewIfNeeded()
  await search.focus()
  await expectCriticalControlInViewport(page, search)
  await spacingStyle.evaluate((element) => element.remove())
  await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' })
  await page.getByRole('button', { name: 'Map', exact: true }).click()
  if (isCompact(page)) {
    await expect(page.getByRole('button', { name: 'Interact with map' })).toBeVisible()
  }
  await expect(page.locator('[data-motion-duration-ms="0"]')).toBeAttached()
  await search.scrollIntoViewIfNeeded()
  await expectCriticalControlInViewport(page, search)
  await axe(page)

  if (!isCompact(page)) {
    await page.getByRole('button', { name: 'Outline' }).click()
    await page.setViewportSize({ width: 320, height: 900 })
    await expect(page.getByRole('button', { name: 'Outline' })).toHaveAttribute('aria-pressed', 'true')
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await search.scrollIntoViewIfNeeded()
    await search.focus()
    await expectCriticalControlInViewport(page, search)
    await expectCriticalControlInViewport(page, page.getByRole('button', { name: 'Outline' }))
    await page.setViewportSize({ width: 1440, height: 900 })
    const textResizeStyle = await page.addStyleTag({ content: 'html { font-size: 200% !important; }' })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await search.scrollIntoViewIfNeeded()
    await search.focus()
    await expectCriticalControlInViewport(page, search)
    await textResizeStyle.evaluate((element) => element.remove())
  }

  const viewport = page.viewportSize()!
  if (isCompact(page)) {
    const mapSurface = page.locator('[data-roadmap-map-surface]')
    await mapSurface.evaluate((element) => {
      const top = element.getBoundingClientRect().top + window.scrollY
      window.scrollTo(0, Math.max(0, top - Math.min(400, window.innerHeight / 2)))
    })
    const mapBounds = await mapSurface.boundingBox()
    expect(mapBounds).not.toBeNull()
    const initialScroll = await page.evaluate(() => window.scrollY)
    const startY = Math.min(viewport.height - 30, Math.max(160, mapBounds!.y + Math.min(mapBounds!.height - 20, 420)))
    const session = await page.context().newCDPSession(page)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: Math.max(20, mapBounds!.x + 20), y: startY }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: Math.max(20, mapBounds!.x + 20), y: Math.max(40, startY - 220) }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(initialScroll)
  } else {
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.mouse.wheel(0, 400)
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBeGreaterThan(0)
  }

  await page.setViewportSize({ width: Math.min(viewport.width, 568), height: 320 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.getByRole('button', { name: 'Outline' }).click()
  const firstItem = page.locator('[data-roadmap-node-id]').first().getByRole('button')
  await firstItem.click()
  const detail = page.getByRole('dialog', { name: /Details for/ })
  await expect(detail).toBeVisible()
  await detail.getByRole('button', { name: 'Set X/Y position' }).click()
  const position = page.getByRole('dialog', { name: /Set position/ })
  await position.getByRole('button', { name: 'Save position' }).scrollIntoViewIfNeeded()
  await expect(position.getByRole('button', { name: 'Save position' })).toBeInViewport()
  await expect(position.getByRole('button', { name: 'Cancel' })).toBeInViewport()
  await axe(page)
})
